import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { THEMES } from "@/lib/themes/catalog.generated";
import { composite, contrast, hueDistance, isDark, isHex, minContrast, parseHex } from "@/lib/themes/color";
import { DEFAULT_DARK_SOURCE, DEFAULT_LIGHT_TOKENS, deriveTheme, TARGETS, type SourcePalette } from "@/lib/themes/derive";
import { THEME_NAMES, themeIdFor } from "@/lib/themes/names";
import { DEFAULT_DARK_ID, DEFAULT_LIGHT_ID, TOKEN_NAMES, TOKEN_VALUE, type ThemeDefinition } from "@/lib/themes/tokens";
import { fromHsl, toHsl } from "@/lib/themes/color";

// Builds the theme catalog from the vendored source palettes, and checks every theme. Run with
// UPDATE_THEMES=1 to rewrite lib/themes/catalog.generated.ts and docs/themes/MAPPING.md.

const ROOT = path.resolve(import.meta.dirname, "../..");
const SOURCE_FILE = path.join(ROOT, "docs/themes/monkeytype-presets.json");
const CATALOG_FILE = path.join(ROOT, "web/lib/themes/catalog.generated.ts");
const MAPPING_FILE = path.join(ROOT, "docs/themes/MAPPING.md");

type SourceEntry = SourcePalette & { hasCss: boolean };
const sources = JSON.parse(readFileSync(SOURCE_FILE, "utf8")) as Record<string, SourceEntry>;

interface Built {
  theme: ThemeDefinition;
  adjustments: string[];
}

function build(): Built[] {
  const built: Built[] = [
    {
      theme: { id: DEFAULT_LIGHT_ID, name: "codebases Light", scheme: "light", source: null, tokens: DEFAULT_LIGHT_TOKENS },
      adjustments: [],
    },
    (() => {
      const derived = deriveTheme(DEFAULT_DARK_SOURCE);
      return {
        theme: { id: DEFAULT_DARK_ID, name: "codebases Dark", scheme: derived.scheme, source: null, tokens: derived.tokens },
        adjustments: derived.adjustments,
      };
    })(),
  ];
  const seen = new Map<string, string>();
  for (const [key, palette] of Object.entries(sources)) {
    const name = THEME_NAMES[key];
    if (!name) throw new Error(`No codebases name for source preset ${key}`);
    let derived = deriveTheme(palette);
    const notes = [...derived.adjustments];
    // Some presets share a palette and differ only by a CSS effect that isn't copied. Shift the
    // accent hue of the later one so no two themes look the same.
    for (let shift = 1; ; shift++) {
      const signature = [derived.tokens.bg, derived.tokens.accent, derived.tokens.text].join();
      const twin = seen.get(signature);
      if (!twin) {
        seen.set(signature, name);
        break;
      }
      const base = toHsl(palette.main);
      const moved = fromHsl({ h: base.h + 40 * shift, s: Math.max(base.s, 60), l: base.l === 100 || base.l === 0 ? 60 : base.l });
      derived = deriveTheme({ ...palette, main: moved, caret: moved });
      notes.push(`accent changed to stay distinct from ${twin}, which has the same source colors`);
    }
    built.push({
      theme: { id: themeIdFor(key), name, scheme: derived.scheme, source: key, tokens: derived.tokens },
      adjustments: notes,
    });
  }
  return built;
}

const built = build();

function catalogSource(): string {
  const lines = built.map(({ theme }) => `  ${JSON.stringify(theme)},`);
  return [
    "// Generated by web/tests/themes.test.ts from docs/themes/monkeytype-presets.json. Don't edit by hand:",
    "// change the source palette, lib/themes/derive.ts or lib/themes/names.ts, then run",
    "// `UPDATE_THEMES=1 npx vitest run tests/themes.test.ts` in web/.",
    'import type { ThemeDefinition } from "./tokens";',
    "",
    "export const THEMES: readonly ThemeDefinition[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

function mappingSource(): string {
  const rows = built
    .filter(({ theme }) => theme.source !== null)
    .map(({ theme, adjustments }) => {
      const css = sources[theme.source ?? ""]?.hasCss ? "custom CSS effect not reproduced; " : "";
      const notes = `${css}${adjustments.join("; ")}` || "none";
      return `| \`${theme.source}\` | \`${theme.id}\` | ${theme.name} | ${theme.scheme} | ${notes} |`;
    });
  return [
    "# Theme mapping",
    "",
    "Generated by `web/tests/themes.test.ts`. Each Monkeytype preset (see README.md for the source revision), the codebases theme adapted from it, and what was changed so it meets codebases' contrast rules. Ratios are against the theme's background.",
    "",
    `${built.length} themes: codebases Light (\`${DEFAULT_LIGHT_ID}\`, the default), codebases Dark (\`${DEFAULT_DARK_ID}\`, the dark half of the System setting), and ${built.length - 2} adapted presets.`,
    "",
    "| Source preset | codebases ID | codebases name | Scheme | Adjustments |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

describe("theme catalog", () => {
  it("is up to date with the source palettes, the derivation and the names", () => {
    if (process.env.UPDATE_THEMES) {
      writeFileSync(CATALOG_FILE, catalogSource());
      writeFileSync(MAPPING_FILE, mappingSource());
    }
    expect(readFileSync(CATALOG_FILE, "utf8")).toBe(catalogSource());
    expect(readFileSync(MAPPING_FILE, "utf8")).toBe(mappingSource());
    expect(THEMES).toEqual(built.map(({ theme }) => theme));
  });

  it("covers every source preset once, plus the two defaults", () => {
    expect(Object.keys(sources)).toHaveLength(187);
    expect(THEMES).toHaveLength(189);
    expect(Object.keys(THEME_NAMES).sort()).toEqual(Object.keys(sources).sort());
    expect(new Set(THEMES.map((theme) => theme.source).filter(Boolean)).size).toBe(187);
  });

  it("has unique IDs and names, none empty, none a source name", () => {
    const ids = THEMES.map((theme) => theme.id);
    const names = THEMES.map((theme) => theme.name.toLowerCase());
    expect(new Set(ids).size).toBe(ids.length);
    expect(new Set(names).size).toBe(names.length);
    for (const theme of THEMES) {
      expect(theme.id).toMatch(/^[a-z0-9]+(-[a-z0-9]+)*$/);
      expect(theme.name.trim()).not.toBe("");
      if (theme.source) expect(theme.name.toLowerCase().replaceAll(" ", "_")).not.toBe(theme.source);
    }
  });

  it("keeps the shipped default light theme exactly as before", () => {
    expect(THEMES[0]).toMatchObject({ id: DEFAULT_LIGHT_ID, scheme: "light", tokens: DEFAULT_LIGHT_TOKENS });
    const css = readFileSync(path.join(ROOT, "web/app/globals.css"), "utf8");
    for (const [token, value] of Object.entries(DEFAULT_LIGHT_TOKENS)) {
      expect(css, `--${token} in globals.css`).toContain(`--${token}: ${value};`);
    }
  });

  it("has no two themes that look the same", () => {
    const signatures = THEMES.map((theme) => [theme.tokens.bg, theme.tokens.accent, theme.tokens.text].join());
    expect(new Set(signatures).size).toBe(signatures.length);
  });
});

describe.each(THEMES.map((theme) => [theme.name, theme] as const))("%s", (_name, theme) => {
  const t = theme.tokens;
  const surfaces = [t.bg, t.panel, t["panel-raised"], t["surface-sunken"], t["input-bg"]];
  const over = (value: string, under: string) => {
    if (isHex(value)) return value;
    const match = /^rgb\((\d+) (\d+) (\d+) \/ (\d+)%\)$/.exec(value);
    if (!match) throw new Error(value);
    const color = `#${[match[1], match[2], match[3]].map((part) => Number(part).toString(16).padStart(2, "0")).join("")}`;
    return composite(color, Number(match[4]) / 100, under);
  };

  it("defines every token with a safe value", () => {
    expect(Object.keys(t).sort()).toEqual([...TOKEN_NAMES].sort());
    for (const [token, value] of Object.entries(t)) expect(value, token).toMatch(TOKEN_VALUE);
    expect(theme.scheme).toBe(isDark(t.bg) ? "dark" : "light");
  });

  it("meets the text contrast targets on every surface", () => {
    expect(minContrast(t.text, surfaces)).toBeGreaterThanOrEqual(theme.id === DEFAULT_LIGHT_ID ? 7 : TARGETS.text);
    for (const token of ["text-muted", "text-faint", "accent-text", "ok", "warn", "bad", "easy", "medium", "hard"] as const) {
      expect(minContrast(t[token], surfaces), token).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    }
    // Selected items use accent text on the soft accent.
    expect(contrast(t["accent-text"], over(t["accent-soft"], t.bg))).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    // Status text on its own soft background.
    expect(contrast(t.ok, over(t["ok-soft"], t.bg))).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    expect(contrast(t.bad, over(t["bad-soft"], t.bg))).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    expect(contrast(t.warn, over(t["warn-soft"], t.bg))).toBeGreaterThanOrEqual(TARGETS.secondaryText);
  });

  it("has readable buttons and visible indicators", () => {
    expect(contrast(t["accent-ink"], t.accent)).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    expect(contrast(t["accent-ink"], t["accent-hover"])).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    expect(contrast(t["bad-ink"], t["bad-fill"])).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    expect(contrast(t["bad-ink"], t["bad-hover"])).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    expect(contrast(t.accent, t.bg)).toBeGreaterThanOrEqual(TARGETS.indicator);
    expect(minContrast(t.focus, surfaces)).toBeGreaterThanOrEqual(TARGETS.indicator);
    expect(contrast(t["heat-4"], t.bg)).toBeGreaterThanOrEqual(TARGETS.indicator);
    expect(contrast(t["chart-line"], t.bg)).toBeGreaterThanOrEqual(TARGETS.indicator);
    // Heatmap steps get darker (or lighter) monotonically away from zero.
    const steps = (["heat-0", "heat-1", "heat-2", "heat-3", "heat-4"] as const).map((token) => contrast(t[token], t.bg));
    for (let index = 1; index < steps.length; index++) expect(steps[index]).toBeGreaterThan(steps[index - 1] ?? 0);
  });

  it("keeps success and failure apart from each other", () => {
    expect(hueDistance(t.ok, t.bad)).toBeGreaterThanOrEqual(60);
    expect(hueDistance(t.ok, t.warn)).toBeGreaterThanOrEqual(30);
  });

  it("has readable code and a white avatar silhouette", () => {
    for (const token of ["syntax-keyword", "syntax-function", "syntax-type", "syntax-string", "syntax-number", "syntax-comment", "editor-line-number"] as const) {
      expect(contrast(t[token], t["editor-bg"]), token).toBeGreaterThanOrEqual(TARGETS.secondaryText);
    }
    expect(t["avatar-fg"]).toBe("#ffffff");
    expect(contrast(t["avatar-fg"], t["avatar-bg"])).toBeGreaterThanOrEqual(4.5);
    const { r, g, b } = parseHex(t["avatar-bg"]);
    expect(Math.max(r, g, b) - Math.min(r, g, b)).toBeLessThan(30); // neutral gray
  });
});
