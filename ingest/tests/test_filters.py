from pathlib import Path

import pytest

from ingest import filter_config
from ingest.filters import SkipReason, detect_language, filter_tree


def _write(root: Path, rel_path: str, content: bytes = b"const a = 1;\n") -> None:
    path = root / rel_path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)


@pytest.mark.parametrize(
    "rel_path",
    [
        "node_modules/x/index.js",
        "vendor/x.js",
        "dist/x.js",
        "build/x.js",
        "packages/a/node_modules/b/c.js",
    ],
)
def test_vendored_dirs_are_dropped(tmp_path: Path, rel_path: str) -> None:
    _write(tmp_path, rel_path)
    assert filter_tree(tmp_path).skipped == {rel_path: SkipReason.VENDORED_DIR}


def test_a_file_named_like_a_vendored_dir_is_kept(tmp_path: Path) -> None:
    _write(tmp_path, "lib/build")
    assert filter_tree(tmp_path).kept == ["lib/build"]


@pytest.mark.parametrize(
    ("rel_path", "content"),
    [("logo.png", b"not really a png"), ("data.txt", b"abc\0def"), ("LOGO.PNG", b"x")],
)
def test_binaries_are_dropped(tmp_path: Path, rel_path: str, content: bytes) -> None:
    _write(tmp_path, rel_path, content)
    assert filter_tree(tmp_path).skipped == {rel_path: SkipReason.BINARY}


def test_nul_byte_past_the_sniff_window_is_not_binary(tmp_path: Path) -> None:
    _write(tmp_path, "data.txt", b"a\n" * filter_config.BINARY_SNIFF_BYTES + b"\0")
    assert filter_tree(tmp_path).kept == ["data.txt"]


@pytest.mark.parametrize(
    ("rel_path", "content"),
    [
        ("package-lock.json", b"{}"),
        ("yarn.lock", b"x"),
        ("api_pb2.py", b"x"),
        ("api.pb.go", b"x"),
        ("types.generated.ts", b"x"),
        ("a.js", b"// @generated by a tool\nconst a = 1;\n"),
        ("b.go", b"// Code generated by protoc. DO NOT EDIT.\npackage b\n"),
    ],
)
def test_generated_files_are_dropped(tmp_path: Path, rel_path: str, content: bytes) -> None:
    _write(tmp_path, rel_path, content)
    assert filter_tree(tmp_path).skipped == {rel_path: SkipReason.GENERATED}


def test_generated_marker_below_the_header_is_kept(tmp_path: Path) -> None:
    _write(tmp_path, "a.js", b"\n" * filter_config.GENERATED_HEADER_LINES + b"// @generated\n")
    assert filter_tree(tmp_path).kept == ["a.js"]


@pytest.mark.parametrize(
    ("rel_path", "content"),
    [
        ("a.min.js", b"short"),
        ("a.min.css", b"short"),
        ("a.js.map", b"{}"),
        ("bundle.js", b"x" * (filter_config.MINIFIED_AVG_LINE_LENGTH + 1)),
    ],
)
def test_minified_files_are_dropped(tmp_path: Path, rel_path: str, content: bytes) -> None:
    _write(tmp_path, rel_path, content)
    assert filter_tree(tmp_path).skipped == {rel_path: SkipReason.MINIFIED}


def test_long_lines_in_data_files_are_not_minified(tmp_path: Path) -> None:
    _write(tmp_path, "data.json", b"x" * (filter_config.MINIFIED_AVG_LINE_LENGTH + 1))
    assert filter_tree(tmp_path).kept == ["data.json"]


def test_size_limit_is_exclusive(tmp_path: Path) -> None:
    _write(tmp_path, "at_limit.txt", b"a" * filter_config.MAX_FILE_BYTES)
    _write(tmp_path, "over_limit.txt", b"a" * (filter_config.MAX_FILE_BYTES + 1))
    result = filter_tree(tmp_path)
    assert result.kept == ["at_limit.txt"]
    assert result.skipped == {"over_limit.txt": SkipReason.TOO_LARGE}


@pytest.mark.parametrize("name", ["LICENSE", "license.md", "LICENCE.txt", "COPYING", "NOTICE"])
def test_license_files_survive_other_rules(tmp_path: Path, name: str) -> None:
    _write(tmp_path, name, b"\0" + b"a" * (filter_config.MAX_FILE_BYTES + 1))
    assert filter_tree(tmp_path).kept == [name]


def test_license_inside_a_vendored_dir_is_dropped(tmp_path: Path) -> None:
    _write(tmp_path, "node_modules/x/LICENSE")
    assert filter_tree(tmp_path).skipped == {"node_modules/x/LICENSE": SkipReason.VENDORED_DIR}


def test_git_dir_is_ignored_and_not_counted(tmp_path: Path) -> None:
    _write(tmp_path, ".git/config")
    _write(tmp_path, "a.js")
    result = filter_tree(tmp_path)
    assert result.kept == ["a.js"]
    assert result.skipped == {}


def test_symlinks_are_never_followed(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "secret.txt").write_text("secret", encoding="utf-8")
    repo = tmp_path / "repo"
    repo.mkdir()
    try:
        (repo / "link.txt").symlink_to(outside / "secret.txt")
        (repo / "link_dir").symlink_to(outside, target_is_directory=True)
    except OSError:
        pytest.skip("creating symlinks needs Developer Mode or admin rights on Windows")
    result = filter_tree(repo)
    assert result.kept == []
    assert result.skipped == {"link.txt": SkipReason.SYMLINK, "link_dir": SkipReason.SYMLINK}


def test_kept_paths_are_sorted_and_use_forward_slashes(tmp_path: Path) -> None:
    _write(tmp_path, "lib/z.js")
    _write(tmp_path, "lib/a/b.js")
    _write(tmp_path, "index.js")
    assert filter_tree(tmp_path).kept == ["index.js", "lib/a/b.js", "lib/z.js"]


def test_skipped_counts_group_by_reason(tmp_path: Path) -> None:
    _write(tmp_path, "dist/a.js")
    _write(tmp_path, "dist/b.js")
    _write(tmp_path, "logo.png")
    assert filter_tree(tmp_path).skipped_by_reason() == {"vendored_dir": 2, "binary": 1}


def test_detect_language() -> None:
    assert detect_language("lib/a.js") == "javascript"
    assert detect_language("LICENSE") == "other"
