"""Every rule deciding which repo files enter a snapshot. Change the rules here, nowhere else."""

import re

# Bytes. "1 MB" in the spec means 1,000,000.
MAX_FILE_BYTES = 1_000_000

# Git metadata, never counted as a skipped file.
IGNORED_DIRS = frozenset({".git"})

VENDORED_DIRS = frozenset({"node_modules", "vendor", "dist", "build"})

# Kept even if another rule would drop them, except inside a vendored dir: spec section 5 requires
# the repo's license in the snapshot, and a vendored dependency's license isn't the repo's.
LICENSE_NAME_RE = re.compile(r"^(UN)?(LICEN[CS]E|COPYING|NOTICE)([.\-_].*)?$", re.IGNORECASE)

BINARY_SNIFF_BYTES = 8192
BINARY_EXTENSIONS = frozenset(
    {
        ".7z", ".a", ".avif", ".bin", ".bmp", ".class", ".dll", ".dylib", ".eot", ".exe", ".gif",
        ".gz", ".ico", ".jar", ".jpeg", ".jpg", ".mov", ".mp3", ".mp4", ".o", ".otf", ".pdf",
        ".png", ".pyc", ".so", ".tar", ".tgz", ".ttf", ".wasm", ".wav", ".webm", ".webp", ".woff",
        ".woff2", ".xz", ".zip",
    }
)  # fmt: skip

GENERATED_FILENAMES = frozenset(
    {
        "bun.lock", "bun.lockb", "Cargo.lock", "composer.lock", "go.sum", "npm-shrinkwrap.json",
        "package-lock.json", "Pipfile.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock",
        "yarn.lock",
    }
)  # fmt: skip
GENERATED_NAME_RE = re.compile(r"(_pb2(_grpc)?\.pyi?|\.pb\.go|\.generated\.[a-z]+|\.g\.dart)$")
GENERATED_HEADER_LINES = 5
GENERATED_HEADER_MARKERS = ("@generated", "DO NOT EDIT", "Code generated by")

MINIFIED_NAME_RE = re.compile(r"(\.min\.[a-z]+|\.map)$")
# Only code and stylesheets: a data file with long lines isn't minified.
MINIFIED_CHECK_EXTENSIONS = frozenset({".cjs", ".css", ".js", ".jsx", ".mjs", ".ts", ".tsx"})
MINIFIED_AVG_LINE_LENGTH = 300

LANGUAGE_BY_EXTENSION = {
    ".cjs": "javascript",
    ".css": "css",
    ".cts": "typescript",
    ".go": "go",
    ".html": "html",
    ".js": "javascript",
    ".json": "json",
    ".jsx": "javascript",
    ".md": "markdown",
    ".mjs": "javascript",
    ".mts": "typescript",
    ".py": "python",
    ".pyi": "python",
    ".sh": "shell",
    ".toml": "toml",
    ".ts": "typescript",
    ".tsx": "typescript",
    ".yaml": "yaml",
    ".yml": "yaml",
}

# What counts as "non-test source" in spec section 5. These only measure a repo. They never drop a
# file from a snapshot, since a puzzle may be about a test.
NON_SOURCE_DIRS = frozenset(
    {
        "__fixtures__", "__mocks__", "__snapshots__", "__test__", "__tests__", "bench",
        "benchmark", "benchmarks", "cypress", "demo", "demos", "doc", "docs", "docs_src", "e2e",
        "example", "examples", "fixture", "fixtures", "integration", "mocks", "perf", "playground",
        "playgrounds", "sample", "samples", "spec", "specs", "test", "test-d", "test-dts",
        "test_data", "testdata", "testing", "tests", "website",
    }
)  # fmt: skip
TEST_FILE_NAME_RE = re.compile(
    r"(\.(test|spec|test-d|bench)\.[cm]?[jt]sx?$|^test_.*\.pyi?$|_test\.pyi?$|^conftest\.py$)"
)
# Other languages in a repo (a Python project's static JS, say) aren't what the indexer reads.
SOURCE_LANGUAGES = {
    "javascript": frozenset({"javascript", "typescript"}),
    "python": frozenset({"python"}),
    "typescript": frozenset({"javascript", "typescript"}),
}
