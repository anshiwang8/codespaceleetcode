"""The Learn path: load content/lessons/, check it, and split it into a public and a private file.

Lessons are authored as YAML (content/schema/lesson.schema.json). Every field is public except each
exercise's `key` and the capstone reflection's `rubric`. `write_generated` writes the public part
to web/lib/learn/course.generated.ts, which pages import on the server and hand to the browser one
lesson at a time, and the keys to web/lib/server/learn/keys.generated.ts, which imports
`server-only`, so a client bundle that reached for it would fail to build. `validate_lessons` runs
in `ingest validate` and also fails when the generated files are out of date.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, cast

import yaml
from jsonschema import Draft202012Validator

from ingest.paths import REPO_ROOT

CONTENT_DIR = REPO_ROOT / "content"
SCHEMA_PATH = CONTENT_DIR / "schema" / "lesson.schema.json"
PUBLIC_OUT = REPO_ROOT / "web" / "lib" / "learn" / "course.generated.ts"
KEYS_OUT = REPO_ROOT / "web" / "lib" / "server" / "learn" / "keys.generated.ts"

REQUIRED_COUNTS = {"lesson": 1, "checkpoint": 3, "capstone": 4}
HEADER = (
    "// Generated by `uv run python -m ingest learn` from content/lessons/. Don't edit by hand:\n"
    "// change the YAML, then run that command from ingest/. `pnpm validate` fails while this\n"
    "// is stale.\n"
)
_LINK = re.compile(r"\]\(([^)\s]+)\)")
_SLUG_OF_PUZZLE = re.compile(r"^[a-z]+-(find|trace|architecture|design)-[0-9]{3}$")


@dataclass
class LessonReport:
    problems: list[str] = field(default_factory=lambda: list[str]())
    lesson_count: int = 0
    exercise_count: int = 0

    @property
    def ok(self) -> bool:
        return not self.problems

    def fail(self, where: str, message: str) -> None:
        self.problems.append(f"{where}: {message}")


@dataclass
class LoadedCourse:
    course: dict[str, Any]
    lessons: dict[str, dict[str, Any]]
    order: list[str]
    placement: dict[str, tuple[str, str | None]]


def lessons_dir(content_dir: Path = CONTENT_DIR) -> Path:
    return content_dir / "lessons"


def _load_yaml(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def _schema_validator() -> Draft202012Validator:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    Draft202012Validator.check_schema(schema)
    return Draft202012Validator(schema)


def _mappings(value: Any) -> list[dict[str, Any]]:
    """A YAML list of mappings, or nothing; anything else is the schema's to report."""
    if not isinstance(value, list):
        return []
    items = cast("list[Any]", value)
    return [cast("dict[str, Any]", item) for item in items if isinstance(item, dict)]


def _items(value: Any) -> list[Any]:
    return cast("list[Any]", value) if isinstance(value, list) else []


def _course_order(
    course: dict[str, Any], report: LessonReport
) -> tuple[list[str], dict[str, tuple[str, str | None]]]:
    """Every slug in course order, with its group and module (None for a checkpoint)."""
    order: list[str] = []
    placement: dict[str, tuple[str, str | None]] = {}
    seen_ids: set[str] = set()
    for group in _mappings(course.get("groups")):
        group_id = str(group.get("id", ""))
        if group_id in seen_ids:
            report.fail("course.yaml", f"group or module id {group_id} is used twice")
        seen_ids.add(group_id)
        checkpoint = group.get("checkpoint")
        before = group.get("checkpoint_before")
        for module in _mappings(group.get("modules")):
            module_id = str(module.get("id", ""))
            if module_id in seen_ids:
                report.fail("course.yaml", f"group or module id {module_id} is used twice")
            seen_ids.add(module_id)
            for slug in _items(module.get("lessons")):
                if checkpoint and before == slug:
                    order.append(str(checkpoint))
                    placement[str(checkpoint)] = (group_id, None)
                order.append(str(slug))
                placement[str(slug)] = (group_id, module_id)
        if checkpoint and str(checkpoint) not in placement:
            if before:
                report.fail(
                    "course.yaml",
                    f"{group_id}'s checkpoint_before {before} isn't one of its lessons",
                )
            order.append(str(checkpoint))
            placement[str(checkpoint)] = (group_id, None)
    duplicates = sorted({slug for slug in order if order.count(slug) > 1})
    for slug in duplicates:
        report.fail("course.yaml", f"{slug} is listed more than once")
    return order, placement


def load_course(content_dir: Path, report: LessonReport) -> LoadedCourse | None:
    directory = lessons_dir(content_dir)
    course_path = directory / "course.yaml"
    if not course_path.is_file():
        report.fail("course.yaml", f"{course_path} doesn't exist")
        return None
    course = _load_yaml(course_path)
    if not isinstance(course, dict):
        report.fail("course.yaml", "isn't a mapping")
        return None
    course = cast("dict[str, Any]", course)
    order, placement = _course_order(course, report)
    validator = _schema_validator()
    lessons: dict[str, dict[str, Any]] = {}
    files = {path.stem: path for path in directory.glob("*.yaml") if path.name != "course.yaml"}
    for stem in sorted(set(files) - set(order)):
        report.fail(f"{stem}.yaml", "isn't listed in course.yaml")
    for slug in order:
        path = files.get(slug)
        if path is None:
            report.fail("course.yaml", f"{slug} has no file content/lessons/{slug}.yaml")
            continue
        try:
            data = _load_yaml(path)
        except yaml.YAMLError as error:
            report.fail(
                f"{slug}.yaml",
                f"isn't valid YAML: {str(error).splitlines()[0]} "
                f"({getattr(error, 'problem_mark', '')})",
            )
            continue
        found = validator.iter_errors(data)  # pyright: ignore[reportUnknownMemberType]
        errors = sorted(found, key=lambda error: list(error.absolute_path))
        for error in errors:
            where = "/".join(str(part) for part in error.absolute_path) or "(top)"
            report.fail(f"{slug}.yaml", f"schema: {where}: {error.message}")
        if errors or not isinstance(data, dict):
            continue
        lesson = cast("dict[str, Any]", data)
        if lesson["slug"] != slug:
            report.fail(f"{slug}.yaml", f"slug {lesson['slug']} doesn't match the file name")
        lessons[slug] = lesson
    return LoadedCourse(course, lessons, order, placement)


def _strings(value: Any) -> Iterator[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in cast("dict[str, Any]", value).values():
            yield from _strings(item)
    elif isinstance(value, list):
        for item in cast("list[Any]", value):
            yield from _strings(item)


def public_part(lesson: dict[str, Any]) -> dict[str, Any]:
    """The lesson without its keys, rubric or author notes."""
    public = {
        key: value
        for key, value in lesson.items()
        if key not in {"author_notes", "reflection", "exercises"}
    }
    public["exercises"] = [
        {key: value for key, value in exercise.items() if key != "key"}
        for exercise in lesson["exercises"]
    ]
    if "reflection" in lesson:
        public["reflection"] = {"prompt": lesson["reflection"]["prompt"]}
    return public


def _answer_tokens(answer: Any) -> set[str]:
    """Strings that would give away a puzzle's answer: its ids, paths and symbol names."""
    tokens: set[str] = set()
    for text in _strings(answer):
        if text in {"symbol", "file", "location", "set", "sequence", "choice"}:
            continue
        tokens.add(text)
        path, _, symbol = text.partition("#")
        tokens.add(path.split(":L")[0])
        if symbol:
            name = symbol.split("~")[0]
            tokens.add(name)
            tokens.add(name.split(".")[-1])
    return {token for token in tokens if len(token) >= 5}


def _mentions(text: str, token: str) -> bool:
    """Whether text names an answer token. A plain lowercase word such as `request` is also
    ordinary English, so it counts only when written as code: in backticks or called."""
    if re.fullmatch(r"[a-z]+", token):
        return f"`{token}`" in text or f"{token}(" in text or f".{token}" in text
    return token in text


def _puzzle_answers(content_dir: Path) -> dict[str, set[str]]:
    answers: dict[str, set[str]] = {}
    for path in sorted((content_dir / "puzzles").glob("*/*.yaml")):
        data = _load_yaml(path)
        if isinstance(data, dict):
            puzzle = cast("dict[str, Any]", data)
            answers[str(puzzle.get("id"))] = _answer_tokens(puzzle.get("answer"))
    return answers


def _check_inline(report: LessonReport, where: str, text: str) -> None:
    if "\n" in text.strip():
        report.fail(where, "must be one line (inline text: `code` and **bold** only)")
    if "```" in text or _LINK.search(text):
        report.fail(where, "inline text can't hold code fences or links")


def _check_markdown(report: LessonReport, where: str, text: str) -> None:
    if re.search(r"```\s*mermaid", text):
        report.fail(where, "lessons don't render mermaid; use a text diagram")
    if re.search(
        r"<[A-Za-z!/]", re.sub(r"`[^`]*`", "", re.sub(r"```.*?```", "", text, flags=re.S))
    ):
        report.fail(where, "raw HTML isn't rendered; write it as Markdown")
    for target in _LINK.findall(text):
        if not (target.startswith("https://") or target.startswith("/")):
            report.fail(where, f"link {target} must be https:// or a site path")


def _check_exercise(
    report: LessonReport,
    slug: str,
    lesson: dict[str, Any],
    exercise: dict[str, Any],
    known: set[str],
) -> None:
    where = f"{slug}.yaml exercise {exercise['id']}"
    kind = exercise["kind"]
    key = exercise["key"]
    answer = key["answer"]
    allowed = {"choice": "choices", "line": "block", "sequence": "candidates"}
    for other_kind, field_name in allowed.items():
        if other_kind != kind and field_name in exercise:
            report.fail(where, f"a {kind} exercise can't have {field_name}")
    if allowed[kind] not in exercise:
        report.fail(where, f"a {kind} exercise needs {allowed[kind]}")
        return
    if kind == "choice":
        ids = [choice["id"] for choice in exercise["choices"]]
        if len(set(ids)) != len(ids):
            report.fail(where, "choice ids must be unique")
        if not isinstance(answer, str) or answer not in ids:
            report.fail(where, f"answer {answer!r} isn't one of its choice ids")
        for choice_id in key.get("feedback", {}):
            if choice_id not in ids:
                report.fail(where, f"feedback for unknown choice {choice_id}")
            elif choice_id == answer:
                report.fail(
                    where, "feedback is for wrong choices; the explanation covers the answer"
                )
        for choice in exercise["choices"]:
            _check_inline(report, f"{where} choice {choice['id']}", choice["label"])
    elif kind == "line":
        blocks = {block["id"]: block for block in lesson.get("code_blocks", [])}
        block = blocks.get(exercise["block"])
        if block is None:
            report.fail(where, f"block {exercise['block']} isn't one of this lesson's code_blocks")
        elif not isinstance(answer, int) or isinstance(answer, bool):
            report.fail(where, "a line exercise's answer is a line number")
        elif answer > len(code_lines(block["source"])):
            report.fail(where, f"line {answer} is past the end of block {block['id']}")
        elif not code_lines(block["source"])[answer - 1].strip():
            report.fail(where, f"line {answer} of block {block['id']} is blank")
    else:
        ids = [candidate["id"] for candidate in exercise["candidates"]]
        if len(set(ids)) != len(ids):
            report.fail(where, "candidate ids must be unique")
        if not isinstance(answer, list):
            report.fail(where, "a sequence exercise's answer is a list of candidate ids")
        else:
            steps = cast("list[Any]", answer)
            if len(set(steps)) != len(steps):
                report.fail(where, "a sequence answer uses each step once")
            for step in steps:
                if step not in ids:
                    report.fail(where, f"answer step {step} isn't a candidate")
            if len(steps) >= len(ids):
                report.fail(
                    where, "a sequence needs at least one candidate that isn't in the answer"
                )
        for candidate in exercise["candidates"]:
            _check_inline(report, f"{where} candidate {candidate['id']}", candidate["label"])
    _check_inline(report, f"{where} explanation", key["explanation"])
    for index, hint in enumerate(key.get("hints", []), start=1):
        _check_inline(report, f"{where} hint {index}", hint)
    for choice_id, text in key.get("feedback", {}).items():
        _check_inline(report, f"{where} feedback {choice_id}", text)
    review = exercise.get("review")
    if review is not None and review not in known:
        report.fail(where, f"review {review} isn't a lesson")


def code_lines(source: str) -> list[str]:
    """A block's lines as the site numbers them: the trailing newline doesn't make an extra line."""
    return source.rstrip("\n").split("\n")


def _check_prerequisites(report: LessonReport, loaded: LoadedCourse) -> None:
    position = {slug: index for index, slug in enumerate(loaded.order)}
    for slug, lesson in loaded.lessons.items():
        for prerequisite in lesson["prerequisites"]:
            if prerequisite not in position:
                report.fail(f"{slug}.yaml", f"prerequisite {prerequisite} isn't in the course")
            elif position[prerequisite] >= position[slug]:
                # Pointing only backwards keeps the graph acyclic and the catalog readable top-down.
                report.fail(
                    f"{slug}.yaml", f"prerequisite {prerequisite} must come earlier in the course"
                )


def validate_lessons(
    content_dir: Path = CONTENT_DIR, *, check_generated: bool = True
) -> LessonReport:
    report = LessonReport()
    if not lessons_dir(content_dir).is_dir():
        # A content folder without lessons (the puzzle fixtures) has nothing to check.
        # test_lessons.py checks the real course, so this can't hide a missing one.
        return report
    loaded = load_course(content_dir, report)
    if loaded is None:
        return report
    known = set(loaded.order)
    references = cast("dict[str, Any]", loaded.course.get("references") or {})
    puzzle_answers = _puzzle_answers(content_dir)
    codes: dict[str, str] = {}
    capstones = [slug for slug, lesson in loaded.lessons.items() if lesson["kind"] == "capstone"]
    if len(capstones) != 1:
        report.fail("course.yaml", f"the course needs exactly one capstone, found {len(capstones)}")
    for slug, lesson in loaded.lessons.items():
        where = f"{slug}.yaml"
        report.lesson_count += 1
        if lesson["code"] in codes:
            report.fail(where, f"code {lesson['code']} is also used by {codes[lesson['code']]}")
        codes[lesson["code"]] = slug
        _group, module = loaded.placement[slug]
        if (module is None) != (lesson["kind"] == "checkpoint"):
            report.fail(
                where, "checkpoints are a group's checkpoint, and every other kind sits in a module"
            )
        if (lesson["kind"] == "capstone") != ("reflection" in lesson):
            report.fail(where, "the capstone, and only the capstone, has a reflection")
        exercise_ids = [exercise["id"] for exercise in lesson["exercises"]]
        if len(set(exercise_ids)) != len(exercise_ids):
            report.fail(where, "exercise ids must be unique")
        required = [exercise for exercise in lesson["exercises"] if exercise["role"] == "required"]
        expected = REQUIRED_COUNTS[lesson["kind"]]
        if len(required) != expected:
            report.fail(
                where,
                f"a {lesson['kind']} has {expected} required exercise(s), not {len(required)}",
            )
        block_ids = [block["id"] for block in lesson.get("code_blocks", [])]
        if len(set(block_ids)) != len(block_ids):
            report.fail(where, "code block ids must be unique")
        for block_id in lesson.get("example", {}).get("blocks", []):
            if block_id not in block_ids:
                report.fail(where, f"example block {block_id} isn't one of code_blocks")
        for exercise in lesson["exercises"]:
            report.exercise_count += 1
            _check_exercise(report, slug, lesson, exercise, known)
        for reference in lesson.get("references", []):
            if reference not in references:
                report.fail(where, f"reference {reference} isn't in course.yaml")
        public_text = list(_strings(public_part(lesson)))
        for name in ("objective", "teach", "scenario", "mistake", "next", "transfer", "after"):
            if name in lesson:
                _check_markdown(report, f"{where} {name}", lesson[name])
        for exercise in lesson["exercises"]:
            _check_markdown(report, f"{where} exercise {exercise['id']} prompt", exercise["prompt"])
        for puzzle_id in lesson.get("practice", []):
            if not _SLUG_OF_PUZZLE.match(puzzle_id) or puzzle_id not in puzzle_answers:
                report.fail(where, f"practice puzzle {puzzle_id} isn't in content/puzzles")
                continue
            for token in sorted(puzzle_answers[puzzle_id]):
                if any(_mentions(text, token) for text in public_text):
                    report.fail(
                        where,
                        f"names {token!r} from {puzzle_id}'s answer; "
                        "lessons never show a puzzle's answer",
                    )
    _check_prerequisites(report, loaded)
    if check_generated and report.ok:
        public, keys = render_generated(loaded)
        for path, text in ((PUBLIC_OUT, public), (KEYS_OUT, keys)):
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                report.fail(
                    path.relative_to(REPO_ROOT).as_posix(),
                    "is out of date: run `uv run python -m ingest learn`",
                )
    return report


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part.title() for part in rest)


def _camelize(value: Any) -> Any:
    if isinstance(value, dict):
        return {
            _camel(str(key)): _camelize(item) for key, item in cast("dict[str, Any]", value).items()
        }
    if isinstance(value, list):
        return [_camelize(item) for item in cast("list[Any]", value)]
    return value


def _module_numbers(
    course: dict[str, Any],
) -> Iterable[tuple[int, dict[str, Any], int, dict[str, Any]]]:
    module_number = 0
    for group_number, group in enumerate(course["groups"], start=1):
        for module in group["modules"]:
            module_number += 1
            yield group_number, group, module_number, module


def render_generated(loaded: LoadedCourse) -> tuple[str, str]:
    """The text of the public and the private generated files."""
    course = loaded.course
    groups: list[dict[str, Any]] = []
    for group_number, group in enumerate(course["groups"], start=1):
        groups.append(
            {
                "id": group["id"],
                "number": group_number,
                "title": group["title"],
                "summary": group["summary"],
                "checkpoint": group.get("checkpoint"),
                "modules": [],
            }
        )
    for group_number, _group, module_number, module in _module_numbers(course):
        groups[group_number - 1]["modules"].append(
            {
                "id": module["id"],
                "number": module_number,
                "title": module["title"],
                "summary": module["summary"],
                "lessons": module["lessons"],
            }
        )
    lessons: dict[str, Any] = {}
    for position, slug in enumerate(loaded.order):
        lesson = loaded.lessons[slug]
        group_id, module_id = loaded.placement[slug]
        public = _camelize(public_part(lesson))
        public["groupId"] = group_id
        public["moduleId"] = module_id
        public["position"] = position
        public.setdefault("topics", [])
        public.setdefault("practice", [])
        public.setdefault("references", [])
        public.setdefault("codeBlocks", [])
        public["requiredIds"] = [
            exercise["id"] for exercise in lesson["exercises"] if exercise["role"] == "required"
        ]
        for exercise, source in zip(public["exercises"], lesson["exercises"], strict=True):
            exercise["hintCount"] = len(source["key"].get("hints", []))
        lessons[slug] = public
    data = {
        "title": course["title"],
        "summary": course["summary"],
        "groups": groups,
        "order": loaded.order,
        "lessons": lessons,
        "references": course["references"],
    }
    public_text = (
        HEADER
        + 'import type { LearnCourse } from "./types";\n\n'
        + f"export const COURSE: LearnCourse = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
    )
    keys: dict[str, Any] = {}
    for slug in loaded.order:
        lesson = loaded.lessons[slug]
        entry: dict[str, Any] = {"revision": lesson["revision"], "exercises": {}}
        for exercise in lesson["exercises"]:
            key = exercise["key"]
            entry["exercises"][exercise["id"]] = {
                "kind": exercise["kind"],
                "role": exercise["role"],
                "answer": key["answer"],
                "explanation": key["explanation"],
                "hints": key.get("hints", []),
                "feedback": key.get("feedback", {}),
            }
        if "reflection" in lesson:
            entry["rubric"] = lesson["reflection"]["rubric"]
        keys[slug] = entry
    keys_text = (
        HEADER
        + 'import "server-only";\n'
        + 'import type { LessonKeys } from "@/lib/server/learn/types";\n\n'
        + "// Answer keys, hints, per-choice feedback and the capstone rubric. Read only by\n"
        + "// web/lib/server/learn/grade.ts; never imported by a page or sent whole to the\n"
        + "// browser.\n"
        + "export const KEYS: Record<string, LessonKeys> = "
        + f"{json.dumps(keys, ensure_ascii=False, indent=2)};\n"
    )
    return public_text, keys_text


def write_generated(content_dir: Path = CONTENT_DIR) -> LessonReport:
    report = validate_lessons(content_dir, check_generated=False)
    if not report.ok:
        return report
    report_for_load = LessonReport()
    loaded = load_course(content_dir, report_for_load)
    if loaded is None:
        return report_for_load
    public, keys = render_generated(loaded)
    PUBLIC_OUT.parent.mkdir(parents=True, exist_ok=True)
    KEYS_OUT.parent.mkdir(parents=True, exist_ok=True)
    PUBLIC_OUT.write_text(public, encoding="utf-8")
    KEYS_OUT.write_text(keys, encoding="utf-8")
    return report


def format_lesson_report(report: LessonReport) -> list[str]:
    lines = [f"  {problem}" for problem in report.problems]
    status = "passed" if report.ok else f"{len(report.problems)} problem(s)"
    lines.append(
        f"Validated {report.lesson_count} lessons and {report.exercise_count} exercises: {status}."
    )
    return lines
